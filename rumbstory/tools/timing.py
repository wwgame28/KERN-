"""Shot timing for each part, driven by the narration.

Each frame of the script gets max(script length, narration/TEMPO + LEAD + TAIL) seconds.
Writes studio/src/timing.js (TIMING[part] = {starts, lens, vo, dur}) and audio/timing.json.
usage: python3 tools/timing.py
"""
import json, os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
TEMPO, LEAD, TAIL, END_HOLD = 1.12, .45, .55, 1.6
SCRIPT = {  # seconds per frame, from the "Время" column
    1: [5, 6, 4, 4, 5, 6, 7, 7, 7, 9],
    2: [5, 6, 8, 6, 5, 4, 8, 7, 6, 5],
    3: [6, 6, 6, 6, 5, 7, 5, 7, 5, 7],
    4: [6, 8, 2, 5, 4, 6, 7, 8, 4, 10],
    5: [6, 7, 6, 6, 7, 7, 4, 5, 5, 7],
}
lines = json.load(open(f"{ROOT}/vo_lines.json"))
dpath = f"{ROOT}/audio/vo/durations.json"
durs = json.load(open(dpath)) if os.path.exists(dpath) else {}

out = {}
for part, script in SCRIPT.items():
    starts, lens, vo, vod, t = [], [], [], [], 0.0
    for i, sl in enumerate(script):
        key = f"p{part}_{i + 1:02d}"
        d = durs.get(key)
        if d is None:  # not generated yet: estimate from the text
            d = len(lines[f"p{part}"][i]) * .085
        d /= TEMPO
        ln = max(sl, LEAD + d + TAIL)
        if i == len(script) - 1:
            ln += END_HOLD
        starts.append(round(t, 3)); lens.append(round(ln, 3)); vo.append(round(t + LEAD, 3)); vod.append(round(d, 3))
        t += ln
    out[part] = {"starts": starts, "lens": lens, "vo": vo, "vod": vod, "dur": round(t, 3)}
    print(f"part {part}: {t:.1f} s")

os.makedirs(f"{ROOT}/studio/src", exist_ok=True)
with open(f"{ROOT}/studio/src/timing.js", "w") as f:
    f.write("// generated by tools/timing.py from the narration lengths: shot starts, lengths, narration starts\n")
    f.write(f"const TEMPO = {TEMPO}, VO_LEAD = {LEAD};\nconst TIMING = {json.dumps(out)};\n")
json.dump({"tempo": TEMPO, "parts": out}, open(f"{ROOT}/audio/timing.json", "w"), indent=1)
